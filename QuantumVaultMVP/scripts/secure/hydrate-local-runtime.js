#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..', '..');
const snapshotEnvRoot = process.env.QV_SECURE_SNAPSHOT_ENV_ROOT
  || path.join(projectRoot, '.secure', 'hetzner-production', 'env');
const backupRoot = path.join(
  projectRoot,
  '.secure',
  'local-runtime-backups',
  new Date().toISOString().replace(/[:]/g, '-'),
);

function ensureDir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true, mode: 0o700 });
}

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return { order: [], map: new Map() };
  }

  const content = fs.readFileSync(filePath, 'utf8');
  const order = [];
  const map = new Map();

  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (!match) {
      continue;
    }
    const key = match[1];
    if (!map.has(key)) {
      order.push(key);
    }
    map.set(key, line);
  }

  return { order, map };
}

function writeEnvFile(targetPath, lines, sourceLabel) {
  ensureDir(path.dirname(targetPath));

  if (fs.existsSync(targetPath)) {
    const backupPath = path.join(backupRoot, path.relative(projectRoot, targetPath));
    ensureDir(path.dirname(backupPath));
    fs.copyFileSync(targetPath, backupPath);
    fs.chmodSync(backupPath, 0o600);
  }

  const header = [
    '# Generated by scripts/secure/hydrate-local-runtime.js',
    `# Source snapshot: ${sourceLabel}`,
    `# Generated at: ${new Date().toISOString()}`,
    '# Do not commit this file.',
    '',
  ].join('\n');
  const body = `${header}${lines.join('\n')}\n`;
  fs.writeFileSync(targetPath, body, { mode: 0o600 });
  fs.chmodSync(targetPath, 0o600);
}

function mergeEnv({ baseFile, overlayFiles = [], outputFile, fixedValues = {}, sourceLabel }) {
  const base = parseEnvFile(baseFile);
  const order = [...base.order];
  const merged = new Map(base.map);

  for (const overlayFile of overlayFiles) {
    const overlay = parseEnvFile(overlayFile);
    for (const key of overlay.order) {
      if (!merged.has(key)) {
        order.push(key);
      }
      merged.set(key, overlay.map.get(key));
    }
  }

  for (const [key, value] of Object.entries(fixedValues)) {
    if (!merged.has(key)) {
      order.push(key);
    }
    merged.set(key, `${key}=${value}`);
  }

  const lines = order
    .filter((key, index) => order.indexOf(key) === index)
    .map((key) => merged.get(key))
    .filter(Boolean);

  writeEnvFile(outputFile, lines, sourceLabel);
  return { outputFile, keyCount: lines.length };
}

const targets = [
  {
    sourceLabel: 'backend/.env <- secure snapshot overlay',
    baseFile: path.join(projectRoot, 'backend', '.env'),
    overlayFiles: [
      path.join(snapshotEnvRoot, 'backend.env'),
      path.join(snapshotEnvRoot, 'root.vault.env'),
    ],
    outputFile: path.join(projectRoot, 'backend', '.env.runtime.local'),
  },
  {
    sourceLabel: 'infra/.env <- secure snapshot overlay',
    baseFile: path.join(projectRoot, 'infra', '.env'),
    overlayFiles: [
      path.join(snapshotEnvRoot, 'infra.env'),
      path.join(snapshotEnvRoot, 'root.vault.env'),
    ],
    outputFile: path.join(projectRoot, 'infra', '.env.runtime.local'),
  },
  {
    sourceLabel: 'frontend/.env.production <- secure snapshot overlay',
    baseFile: path.join(projectRoot, 'frontend', '.env.production'),
    overlayFiles: [
      path.join(snapshotEnvRoot, 'frontend.env.production'),
    ],
    fixedValues: {
      NEXT_PUBLIC_BASE_PATH: '/QuantumVaultMVP',
    },
    outputFile: path.join(projectRoot, 'frontend', '.env.production.local'),
  },
  {
    sourceLabel: 'main-frontend/.env.production <- secure snapshot overlay',
    baseFile: path.join(projectRoot, 'main-frontend', '.env.production'),
    overlayFiles: [
      path.join(snapshotEnvRoot, 'main-frontend.env.production'),
    ],
    outputFile: path.join(projectRoot, 'main-frontend', '.env.production.local'),
  },
];

ensureDir(backupRoot);

const results = targets.map(mergeEnv);

for (const result of results) {
  console.log(`hydrated ${path.relative(projectRoot, result.outputFile)} (${result.keyCount} keys)`);
}

console.log(`backups stored under ${path.relative(projectRoot, backupRoot)}`);
